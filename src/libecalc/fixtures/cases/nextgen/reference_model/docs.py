import re
from pathlib import Path

from libecalc.presentation.yaml.yaml_types.components.yaml_asset import YamlAsset

from .export import ARCHIVE_FILE_NAME, MODEL_FILE_NAME, example_files
from .mermaid import energy_network_to_mermaid
from .model import build_reference_model

PAGE_FILE_NAME = "examples.mdx"
ARCHIVE_URL_PREFIX = "/examples/nextgen"
_GENERATED_COMMENT = "{/* Generated by src/generate_fixture.py. Do not edit. */}"


def _code_block(title: str, content: str, language: str = "text") -> str:
    longest_backtick_run = max((len(run) for run in re.findall(r"`+", content)), default=0)
    fence = "`" * max(3, longest_backtick_run + 1)
    return f'{fence}{language} title="{title}"\n{content.rstrip()}\n{fence}'


def render_example_page(model: YamlAsset | None = None, files: dict[str, str] | None = None) -> str:
    model = model if model is not None else build_reference_model()
    files = files if files is not None else example_files(model)
    model_block = _code_block(MODEL_FILE_NAME, files[MODEL_FILE_NAME], "yaml")
    resource_blocks = "\n\n".join(
        _code_block(name, content) for name, content in files.items() if name != MODEL_FILE_NAME
    )

    return f"""\
---
title: NextGen example
sidebar_label: Example
sidebar_position: 5
description: A complete example of a NextGen eCalc model.
---

{_GENERATED_COMMENT}

# NextGen model example

## Energy network {{/* #energy-network */}}

```mermaid
{energy_network_to_mermaid(model)}
```

The energy network is shown at the top, and the energy demand from the process model (compressors and process
pipelines) is shown in orange at the bottom.

This is an example of a NextGen eCalc model.
It is generated from the model builders in the eCalc library, and verified by the library tests.
See the [Process Reference](./process-reference.mdx) and the [Energy Reference](./energy-reference.mdx) for a
description of every element, and the [NextGen changelog](../../changelog/nextgen.md) for what changed between
releases.

The model contains:

- Four export trains with two compressors each, defined in `COMPRESSORS`, placed on a `SHAFTS` entry per train, and run in
  `PROCESS_PIPELINES` with a compressor model from `DEFINITIONS.COMPRESSOR_MODELS`.
- A `TIMELINE` event that rebundles the compressors of the first export train.
- One `PROCESS_SIMULATIONS` entry that distributes a common inlet stream between the export trains, with constraints for each
  train.
- Two pumps defined in `PUMPS`, run in `PUMP_PIPELINES` with a pump model from `DEFINITIONS.PUMP_MODELS`, and one
  `PUMP_SIMULATIONS` entry that distributes a common liquid inlet stream between the pump pipelines.
- An `ENERGY_NETWORK` with fuel gas and electrical sources, generator, gas turbines, electrical cable and motors, drive
  trains for the export trains, an electrical consumer, and sampled compressors driven by an electrical motor and by
  a gas turbine.
- `MECHANICAL_EFFICIENCIES` on `export_train_1_drive`, for both compressors on its shaft, and on `export_train_2_el`,
  for one compressor. The other compressor has efficiency 1.0.

## Download {{/* #download */}}

[Download {ARCHIVE_FILE_NAME}]({ARCHIVE_URL_PREFIX}/{ARCHIVE_FILE_NAME}) with the YAML
model, the input files and `export_info.json`.

## Full eCalc YAML model {{/* #full-ecalc-yaml-model */}}

{model_block}

### Input files {{/* #input-files */}}

{resource_blocks}
"""


def export_example_page(
    docs_directory: Path, model: YamlAsset | None = None, files: dict[str, str] | None = None
) -> Path:
    docs_directory.mkdir(parents=True, exist_ok=True)
    page_path = docs_directory / PAGE_FILE_NAME
    page_path.write_text(render_example_page(model, files))
    return page_path
