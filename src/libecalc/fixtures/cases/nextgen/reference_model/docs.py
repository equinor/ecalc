import re
from pathlib import Path

from libecalc.presentation.yaml.yaml_types.yaml_version import LATEST_YAML_VERSION

from .export import MODEL_FILE_NAME, archive_file_name, resource_paths, version_directory_name
from .mermaid import energy_network_to_mermaid
from .model import build_reference_model

PAGE_SUFFIX = ".mdx"
INDEX_FILE_NAME = "index.md"
ARCHIVE_URL_PREFIX = "/examples/nextgen"
_PAGE_NAME = re.compile(r"^v(\d+)\.mdx$")
_GENERATED_COMMENT = "{/* Generated by src/generate_fixture.py. Do not edit. */}"


def release_status(yaml_version: int) -> str:
    return "In development" if yaml_version == LATEST_YAML_VERSION else "In production"


def release_label(yaml_version: int) -> str:
    return f"{release_status(yaml_version)} (v{yaml_version})"


def _import_name(index: int) -> str:
    return f"resource{index}"


def render_example_page(yaml_version: int) -> str:
    version_directory = version_directory_name(yaml_version)
    resources = resource_paths()
    label = release_label(yaml_version)

    imports = "\n".join(
        [
            "import CodeBlock from '@theme/CodeBlock';",
            f"import yamlModel from '!!raw-loader!@examples/nextgen/{version_directory}/{MODEL_FILE_NAME}';",
            *(
                f"import {_import_name(index)} from '!!raw-loader!@examples/nextgen/{version_directory}/{path.name}';"
                for index, path in enumerate(resources)
            ),
        ]
    )
    resource_blocks = "\n".join(
        f'<CodeBlock title="{path.name}">{{{_import_name(index)}}}</CodeBlock>' for index, path in enumerate(resources)
    )

    return f"""\
---
title: NextGen example, {label}
sidebar_label: {label}
sidebar_position: {yaml_version}
description: A complete example of a NextGen eCalc model for YAML_VERSION {yaml_version}.
---

{_GENERATED_COMMENT}

{imports}

# NextGen model example, {label}

## Energy network {{/* #energy-network */}}

```mermaid
{energy_network_to_mermaid(build_reference_model(yaml_version))}
```

The energy network is shown at the top, and the energy demand from the process model (compressors and process
pipelines) is shown in orange at the bottom.

This is an example of a NextGen eCalc model using `YAML_VERSION: {yaml_version}`, which is {release_status(yaml_version).lower()}.
It is generated from the model builders in the eCalc library, and verified by the library tests.
See the [Process Reference](../process-reference.mdx) and the [Energy Reference](../energy-reference.mdx) for a
description of every element, and the [YAML Changelog](../yaml-changelog/index.md) for what changed between versions.

The model contains:

- Four export trains with two compressors each, defined in `COMPRESSORS`, placed on a `SHAFTS` entry per train, and run in
  `PROCESS_PIPELINES` with a compressor model from `DEFINITIONS.COMPRESSOR_MODELS`.
- A `TIMELINE` event that rebundles the compressors of the first export train.
- One `PROCESS_SIMULATIONS` entry that distributes a common inlet stream between the export trains, with constraints for each
  train.
- An `ENERGY_NETWORK` with fuel gas and electrical sources, generator, gas turbines, electrical cable and motors, drive
  trains for the export trains, an electrical consumer, and sampled compressors that are driven electrically,
  mechanically and by fuel.
- `MECHANICAL_EFFICIENCIES` on `export_train_1_drive`, for both compressors on its shaft, and on `export_train_2_el`,
  for one compressor. The other compressor has efficiency 1.0.

## Download {{/* #download */}}

[Download {archive_file_name(yaml_version)}]({ARCHIVE_URL_PREFIX}/{archive_file_name(yaml_version)}) with the YAML
model, the input files and `export_info.json`.

## Full eCalc YAML model {{/* #full-ecalc-yaml-model */}}

<CodeBlock title="{MODEL_FILE_NAME}" language="yaml">{{yamlModel}}</CodeBlock>

### Input files {{/* #input-files */}}

{resource_blocks}
"""


def _existing_page_versions(docs_directory: Path) -> list[int]:
    return sorted(
        (
            int(match.group(1))
            for path in docs_directory.glob(f"*{PAGE_SUFFIX}")
            if (match := _PAGE_NAME.match(path.name))
        ),
        reverse=True,
    )


def render_example_index(yaml_versions: list[int]) -> str:
    links = "\n".join(
        f"- [{release_label(version)}](./{version_directory_name(version)}.mdx)" for version in yaml_versions
    )
    return f"""\
---
title: NextGen examples
sidebar_position: 0
description: NextGen example models for the supported YAML versions.
---

# NextGen examples

Example NextGen models, generated from the model builders in the eCalc library, one for each `YAML_VERSION`.

{links}
"""


def export_example_pages(docs_directory: Path, yaml_version: int = LATEST_YAML_VERSION) -> list[Path]:
    docs_directory.mkdir(parents=True, exist_ok=True)
    page_path = docs_directory / f"{version_directory_name(yaml_version)}{PAGE_SUFFIX}"
    page_path.write_text(render_example_page(yaml_version))

    index_path = docs_directory / INDEX_FILE_NAME
    index_path.write_text(render_example_index(_existing_page_versions(docs_directory)))
    return [index_path, page_path]
