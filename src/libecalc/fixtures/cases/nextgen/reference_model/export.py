import io
import json
import re
import shutil
import zipfile
from datetime import date
from pathlib import Path
from typing import Any

import yaml

from libecalc.presentation.yaml.yaml_types.components.yaml_asset import YamlAsset
from libecalc.presentation.yaml.yaml_types.yaml_version import LATEST_YAML_VERSION

from .model import RESOURCE_DIRECTORY, build_reference_model

MODEL_FILE_NAME = "model.yaml"
RESOURCE_SUFFIX = ".csv"
ARCHIVE_SUFFIX = ".zip"
EXPORT_INFO_FILE_NAME = "export_info.json"
EXPORT_INFO_AUTHOR = "fg_ecalc@equinor.com"
_ARCHIVE_TIMESTAMP = (1980, 1, 1, 0, 0, 0)
_EXPORT_INFO_DATE = re.compile(r"- (\d{4}-\d{2}-\d{2}) - v\d+")
_MIDNIGHT_DATETIME = re.compile(r"^(\d{4}-\d{2}-\d{2})T00:00:00$")
_VERSION_DIRECTORY = re.compile(r"^v\d+$")
_NUMBER = re.compile(r"^-?\d+(\.\d+)?$")
_EXPRESSION_KEY = "VALUE"

GENERATED_HEADER = (
    "# Generated by src/generate_fixture.py from libecalc.fixtures.cases.nextgen.reference_model. Do not edit.\n"
)


class _ModelDumper(yaml.SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def _represent_list(dumper: yaml.SafeDumper, data: list):
    is_flat = not any(isinstance(item, dict | list) for item in data)
    return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=is_flat)


_ModelDumper.add_representer(list, _represent_list)


def _to_number(text: str) -> int | float:
    return float(text) if "." in text else int(text)


def _simplify(data: Any, key: str | None = None) -> Any:
    if isinstance(data, dict):
        return {name: _simplify(value, name) for name, value in data.items()}
    if isinstance(data, list):
        return [_simplify(item) for item in data]
    if isinstance(data, str):
        midnight = _MIDNIGHT_DATETIME.match(data)
        if midnight:
            return date.fromisoformat(midnight.group(1))
        if key == _EXPRESSION_KEY and _NUMBER.match(data):
            return _to_number(data)
    return data


def render_model_yaml(model: YamlAsset) -> str:
    data = model.model_dump(mode="json", exclude_unset=True, by_alias=True)
    body = yaml.dump(_simplify(data), Dumper=_ModelDumper, default_flow_style=False, sort_keys=False, width=120)
    return GENERATED_HEADER + body


def resource_paths() -> list[Path]:
    return sorted(RESOURCE_DIRECTORY.glob(f"*{RESOURCE_SUFFIX}"))


def generated_file_names(directory: Path) -> list[str]:
    return sorted(
        path.name for path in directory.iterdir() if path.name == MODEL_FILE_NAME or path.suffix == RESOURCE_SUFFIX
    )


def version_directory_name(yaml_version: int) -> str:
    return f"v{yaml_version}"


def all_example_yaml_versions() -> list[int]:
    return [LATEST_YAML_VERSION - 1, LATEST_YAML_VERSION]


def example_yaml_versions(include_previous: bool = False) -> list[int]:
    return all_example_yaml_versions() if include_previous else [LATEST_YAML_VERSION]


def export_reference_model(output_directory: Path, yaml_version: int = LATEST_YAML_VERSION) -> list[Path]:
    output_directory.mkdir(parents=True, exist_ok=True)
    for file_name in generated_file_names(output_directory):
        (output_directory / file_name).unlink()

    model_path = output_directory / MODEL_FILE_NAME
    model_path.write_text(render_model_yaml(build_reference_model(yaml_version)))

    resource_copies = [Path(shutil.copy(path, output_directory / path.name)) for path in resource_paths()]
    return [model_path, *resource_copies]


def export_reference_models(output_directory: Path, include_previous: bool = False) -> list[Path]:
    output_directory.mkdir(parents=True, exist_ok=True)
    kept_directory_names = {version_directory_name(version) for version in all_example_yaml_versions()}
    for path in output_directory.iterdir():
        if path.is_file() and (path.name == MODEL_FILE_NAME or path.suffix == RESOURCE_SUFFIX):
            path.unlink()
        elif path.is_dir() and _VERSION_DIRECTORY.match(path.name) and path.name not in kept_directory_names:
            shutil.rmtree(path)

    return [
        path
        for version in example_yaml_versions(include_previous)
        for path in export_reference_model(output_directory / version_directory_name(version), version)
    ]


def archive_file_name(yaml_version: int) -> str:
    return f"example_model_{version_directory_name(yaml_version)}{ARCHIVE_SUFFIX}"


def _render_export_info(yaml_version: int, export_date: str) -> bytes:
    info = {
        "author": EXPORT_INFO_AUTHOR,
        "model_name": f"Example model - eCalc NextGen - {export_date} - {version_directory_name(yaml_version)}",
        "is_next_gen": True,
    }
    return json.dumps(info, separators=(",", ":")).encode()


def _build_archive(model_directory: Path, yaml_version: int, export_date: str) -> bytes:
    files = {
        EXPORT_INFO_FILE_NAME: _render_export_info(yaml_version, export_date),
        **{name: (model_directory / name).read_bytes() for name in generated_file_names(model_directory)},
    }
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for name in sorted(files):
            info = zipfile.ZipInfo(name, _ARCHIVE_TIMESTAMP)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, files[name])
    return buffer.getvalue()


def _existing_export_date(archive_path: Path) -> str | None:
    if not archive_path.exists():
        return None
    with zipfile.ZipFile(archive_path) as archive:
        if EXPORT_INFO_FILE_NAME not in archive.namelist():
            return None
        match = _EXPORT_INFO_DATE.search(archive.read(EXPORT_INFO_FILE_NAME).decode())
    return match.group(1) if match else None


def export_example_archive(archive_directory: Path, model_directory: Path, yaml_version: int) -> Path:
    archive_directory.mkdir(parents=True, exist_ok=True)
    archive_path = archive_directory / archive_file_name(yaml_version)
    existing_date = _existing_export_date(archive_path)
    if existing_date is not None:
        unchanged = _build_archive(model_directory, yaml_version, existing_date)
        if archive_path.read_bytes() == unchanged:
            return archive_path
    archive_path.write_bytes(_build_archive(model_directory, yaml_version, date.today().isoformat()))
    return archive_path


def export_example_archives(
    archive_directory: Path, output_directory: Path, include_previous: bool = False
) -> list[Path]:
    archive_directory.mkdir(parents=True, exist_ok=True)
    kept_names = {archive_file_name(version) for version in all_example_yaml_versions()}
    for path in archive_directory.glob(f"example_model_v*{ARCHIVE_SUFFIX}"):
        if path.name not in kept_names:
            path.unlink()
    return [
        export_example_archive(archive_directory, output_directory / version_directory_name(version), version)
        for version in example_yaml_versions(include_previous)
    ]
